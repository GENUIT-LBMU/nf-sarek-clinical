#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────────────
# mirror_images.sh — Camino B: mirror all 7 images into the org registry and
#                    pin them by sha256 digest (clinical-grade reproducibility)
# ──────────────────────────────────────────────────────────────────────────────
# What it does:
#   1. Builds + pushes the 3 custom images (civicpy, r-annotation, sigprofiler).
#   2. Copies the 6 public images (snpeff 5.1 + 5.2, spliceai, bcftools, gatk, hrprofiler) from their
#      upstream registries into ${MIRROR_REGISTRY}, preserving the manifest
#      (registry-to-registry, no local pull) via `docker buildx imagetools`.
#   3. Captures each image's immutable sha256 digest and regenerates
#      conf/containers.mirror.config with digest-pinned references.
#
# After running, use the mirrored, pinned images with:
#   nextflow run ... -profile docker,mirror      # or singularity,mirror
#
# Prerequisites:
#   - docker + buildx (already bundled with Docker Desktop / recent engines)
#   - Write access to ${MIRROR_REGISTRY}; log in first, e.g.:
#       echo "$GHCR_TOKEN" | docker login ghcr.io -u <user> --password-stdin
#
# Environment variables:
#   MIRROR_REGISTRY   Destination namespace (default: ghcr.io/genuit-lbmu).
#                     Must be lowercase (registry requirement).
# ──────────────────────────────────────────────────────────────────────────────
set -euo pipefail

MIRROR_REGISTRY="${MIRROR_REGISTRY:-ghcr.io/genuit-lbmu}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT_CONFIG="${REPO_DIR}/conf/containers.mirror.config"

# Lowercase guard (ghcr.io rejects uppercase path segments)
if [[ "${MIRROR_REGISTRY}" != "${MIRROR_REGISTRY,,}" ]]; then
    echo "ERROR: MIRROR_REGISTRY must be lowercase: '${MIRROR_REGISTRY}'" >&2
    exit 1
fi

echo "════════════════════════════════════════════════════════════════════════"
echo "  Mirroring 7 images → ${MIRROR_REGISTRY}  (digest-pinned)"
echo "════════════════════════════════════════════════════════════════════════"

# label | upstream source                                   | dest repo:tag
PUBLIC=(
    "snpsift|quay.io/biocontainers/snpeff:5.1--hdfd78af_2|snpeff:5.1--hdfd78af_2"
    "snpeff_mane|quay.io/biocontainers/snpeff:5.2--hdfd78af_1|snpeff:5.2--hdfd78af_1"
    "spliceai|quay.io/biocontainers/spliceai:1.3.1--pyh864c0ab_1|spliceai:1.3.1--pyh864c0ab_1"
    "bcftools|quay.io/biocontainers/bcftools:1.20--h8b25389_0|bcftools:1.20--h8b25389_0"
    "gatk|broadinstitute/gatk:4.6.2.0|gatk:4.6.2.0"
    "hrprofiler|florpio/hrprofiler:1.0-full|hrprofiler:1.0-full"
)
# label | dockerfile                | dest repo:tag
CUSTOM=(
    "civicpy|Dockerfile.civicpy|civicpy:5.2.0"
    "r_base|Dockerfile.r_annotation|r-annotation:1.0.0"
    "sigprofiler|Dockerfile.sigprofiler|sigprofiler:0.1.7"
)

declare -A REF   # label → fully-qualified digest-pinned reference

inspect_digest() {
    # Print the manifest digest (sha256:...) of a pushed image
    docker buildx imagetools inspect "$1" --format '{{.Manifest.Digest}}'
}

# ── 1. Build + push the custom images ─────────────────────────────────────────
echo ""
echo "── Building + pushing custom images ─────────────────────────────────────"
for entry in "${CUSTOM[@]}"; do
    IFS='|' read -r label dockerfile dest <<< "${entry}"
    target="${MIRROR_REGISTRY}/${dest}"
    repo="${dest%%:*}"
    echo "  [build] ${label} → ${target}"
    docker buildx build \
        --platform linux/amd64 \
        -f "${SCRIPT_DIR}/${dockerfile}" \
        -t "${target}" \
        --push \
        "${SCRIPT_DIR}"
    digest="$(inspect_digest "${target}")"
    REF[$label]="${MIRROR_REGISTRY}/${repo}@${digest}"
    echo "         pinned: ${REF[$label]}"
done

# ── 2. Mirror the public images (registry → registry, no local pull) ──────────
echo ""
echo "── Mirroring public images ──────────────────────────────────────────────"
for entry in "${PUBLIC[@]}"; do
    IFS='|' read -r label src dest <<< "${entry}"
    target="${MIRROR_REGISTRY}/${dest}"
    repo="${dest%%:*}"
    echo "  [copy] ${src} → ${target}"
    docker buildx imagetools create --tag "${target}" "${src}"
    digest="$(inspect_digest "${target}")"
    REF[$label]="${MIRROR_REGISTRY}/${repo}@${digest}"
    echo "         pinned: ${REF[$label]}"
done

# ── 3. Regenerate the digest-pinned Nextflow config ───────────────────────────
echo ""
echo "── Writing ${OUT_CONFIG} ────────────────────────────────────────────────"
cat > "${OUT_CONFIG}" <<EOF
/*
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    Digest-pinned mirrored container images (Camino B)
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    GENERATED by docker/mirror_images.sh — do not edit by hand.
    Enable with:  -profile docker,mirror   (or  singularity,mirror)

    Every image is referenced by its immutable sha256 digest in the org registry
    (${MIRROR_REGISTRY}). "Same version" here means literally the same bytes,
    verified at pull time, independent of upstream registries.

    To update a tool: bump the tag in docker/mirror_images.sh, re-run it, commit
    the regenerated digest below.
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
*/

process {
    withLabel:snpsift     { container = '${REF[snpsift]}' }      // snpeff 5.1
    withLabel:snpeff_mane { container = '${REF[snpeff_mane]}' }  // snpeff 5.2 (MANE re-annotation)
    withLabel:spliceai    { container = '${REF[spliceai]}' }     // spliceai 1.3.1
    withLabel:bcftools    { container = '${REF[bcftools]}' }     // bcftools 1.20
    withLabel:gatk        { container = '${REF[gatk]}' }         // gatk 4.6.2.0
    withLabel:hrprofiler  { container = '${REF[hrprofiler]}' }   // hrprofiler 1.0-full
    withLabel:r_base      { container = '${REF[r_base]}' }       // r-annotation 1.0.0
    withLabel:civicpy     { container = '${REF[civicpy]}' }      // civicpy 5.2.0
    withLabel:sigprofiler { container = '${REF[sigprofiler]}' }  // sigprofiler (SPA 1.1.3)
}
EOF

echo ""
echo "════════════════════════════════════════════════════════════════════════"
echo "  Done. 7 images mirrored and pinned in:"
echo "    ${OUT_CONFIG}"
echo ""
echo "  Run the pipeline against the pinned mirror with:"
echo "    nextflow run ... -profile docker,mirror"
echo "  Review + commit the regenerated config to lock it in."
echo "════════════════════════════════════════════════════════════════════════"
